  page.net.on("/api/upload/chunk", () => ({ status: 200, body: {} }));
  const api = async (url, opts) => {
    calls.push({ url: String(url), opts: opts || {} });
    if (url === "/api/print3d/state") {
      return {
        ok: true, printers: [], history: [], queue: [], maintenance: [],
        config: { printers: [{ id: "p1", name: "A1", kind: "bambu", bed: { x: 256, y: 256, z: 256 } }], makerworld: {} },
        makerworld: {},
      };
    }
    if (url === "/api/upload/init") return { id: "up-gx-1", chunk: 1024 };
    if (url === "/api/upload/complete") return { ok: true, name: "dropped.gx", rel: "Print/dropped.gx", size: 18 };
    if (url === "/api/print3d/models/rescan") { rescanned = true; return { ok: true }; }
    if (String(url).startsWith("/api/print3d/models?")) {
      return {
        ok: true,
        models: [{ id: "m-gx-1", name: "dropped.gx", rel: "dropped.gx", ext: "gx", size: 18, mtime: 999 }],
        total: 1, indexed: 1, tags: [],
      };
    }
    if (String(url).startsWith("/api/print3d/models/inspect")) {
      return { ok: true, info: { kind: "gcode", plates: [1], filaments: [] } };
    }
    return { ok: true };
  };

  let loadedModelId = "";
  w.HQGcode = {
    FEATURE_LEGEND: [],
    TOOL_PALETTE_HEX: ["#38bdf8"],
    createGcodeViewer: () => ({
      load: async (opts) => {
        loadedModelId = opts.modelId;
        return {
          ok: true, colorMode: "moveKind",
          summary: {
            layerCount: 1, segmentCount: 5, layerZs: new Float32Array([0.2]),
            dimensionsMm: [10, 10, 0.2], dimensionsSource: "model",
            tools: [{ id: 0 }], filaments: [],
            availableColorModes: ["single", "moveKind"], colorSource: "none",
            totalTimeMs: null, timeEstimateSource: "none", complete: true,
          },
        };
      },
      setLayerRange() {}, getLayerZ: () => 0.2, setColorMode: () => true,
      setShowTravel() {}, setShowRetractions() {}, setShowVolumeCage() {},
      setFeatureRoleVisible() {}, setScrub() {}, setView() {},
      resetCamera() {}, resize() {}, getSummary: () => null, dispose() {},
    }),
  };

  const everyNode = (root, out = []) => {
    for (const c of root.children || []) {
      if (c.nodeType === 1) { out.push(c); everyNode(c, out); }
    }
    return out;
  };
  const findBtn = (root, text) => everyNode(root).find((n) => n.tagName === "BUTTON" && n.textContent.trim() === text);
  const findCls = (root, cls) => everyNode(root).find((n) => String(n.className || "").split(/\s+/).includes(cls));

  const host = d.createElement("section");
  d.body.append(host);
  w.HqPrint3d.show(host, api);
  await tick(20);

  const studioTab = everyNode(host).find((n) => n.getAttribute && n.getAttribute("data-tab") === "studio");
  studioTab.click();
  await tick(20);

  assert.ok(findBtn(host, "Ouvrir un fichier…"), "Studio toolbar has 'Ouvrir un fichier…' button");
  const fileIn = findCls(host, "p3d-studio-file");
  const acceptStr = fileIn ? String((fileIn.getAttribute && fileIn.getAttribute("accept")) || fileIn.accept || "") : "";
  assert.ok(acceptStr.includes(".gcode") && acceptStr.includes(".gx"), "hidden file input accepts .gcode and .gx");

  // Unsupported extension via drop/open does not start upload
  const studioPane = everyNode(host).find((n) => String(n.className || "").split(/\s+/).includes("p3d-studio-pane"));
