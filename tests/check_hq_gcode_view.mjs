  assert.equal(calls.filter((c) => c.url === "/api/upload/init").length, 0, "unsupported extension rejected before upload");

  // Drop valid .gx file onto Studio pane -> dragover class toggles, upload runs, rescans, and opens 3D preview
  const gxBuf = new TextEncoder().encode("G90\nG1 X10 Y10 E1\n").buffer;
