function createBundledParseWorker() {
  const src = readFileSync(new URL("../assets/vendor-gcode-worker.js", import.meta.url), "utf8");
  const listeners = { onmessage: null, onerror: null };
  let terminated = false;
  const selfCtx = {
    postMessage(msg) {
      if (terminated) return;
      if (typeof listeners.onmessage === "function") {
        queueMicrotask(() => { if (!terminated && listeners.onmessage) listeners.onmessage({ data: msg }); });
      }
    },
    onmessage: null,
  };
  const sandbox = {
    self: selfCtx,
    TextDecoder,
    TextEncoder,
    Uint8Array,
    Uint16Array,
    Uint32Array,
    Float32Array,
    Float64Array,
    Int32Array,
    ArrayBuffer,
    DataView,
    Map,
    Set,
    WeakMap,
    Promise,
    Error,
    TypeError,
    RangeError,
    Math,
    Number,
    String,
    Array,
    Object,
    JSON,
    Date,
    RegExp,
    MessageChannel: globalThis.MessageChannel,
    setTimeout,
    clearTimeout,
    queueMicrotask,
    console,
  };
  sandbox.globalThis = sandbox;
  vm.runInNewContext(src, sandbox, { filename: "vendor-gcode-worker.js" });
  return {
    set onmessage(fn) { listeners.onmessage = fn; },
    get onmessage() { return listeners.onmessage; },
    set onerror(fn) { listeners.onerror = fn; },
    get onerror() { return listeners.onerror; },
    get terminated() { return terminated; },
    postMessage(msg) {
      if (terminated) return;
      queueMicrotask(() => {
        if (!terminated && typeof selfCtx.onmessage === "function") {
          selfCtx.onmessage({ data: msg });
        }
      });
    },
    terminate() { terminated = true; },
  };
}

function parseWithBundledWorker(gcodeText) {
  const w = createBundledParseWorker();
  const bytes = new TextEncoder().encode(gcodeText);
  return new Promise((resolve, reject) => {
    w.onmessage = (ev) => {
      const m = ev.data;
      if (m.type === "done") { w.terminate(); resolve(m); }
      else if (m.type === "error") { w.terminate(); reject(new Error(m.error.code + ": " + m.error.message)); }
    };
    w.onerror = (err) => { w.terminate(); reject(err); };
    w.postMessage({ v: 1, type: "parse", id: 1, input: bytes, opts: {} });
  });
}

