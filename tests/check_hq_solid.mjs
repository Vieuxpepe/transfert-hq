import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const S = require("../assets/hq-sketch-core.js");

const d = S.createDoc({ units: "mm" });
assert.equal(d.version, 2);
const rect = S.addRect(d, { x: 0, y: 0 }, { x: 100, y: 50 });
let r = S.addFeature(d, "extrude", rect.lines, 20, "blind");
assert.equal(r.ok, true);
assert.equal(S.validateDoc(r.doc).ok, true);
let model = r.doc;
const hole = S.addCircle(model, { x: 50, y: 25 }, 8);
r = S.addFeature(model, "cut", [hole], 0, "throughAll");
assert.equal(r.ok, true);
model = r.doc;
assert.equal(model.features.length, 2);
assert.equal(S.validateDoc(model).ok, true);
let changed = S.convertUnits(model, "cm");
assert.equal(changed.ok, true);
assert.equal(changed.doc.features[0].depth, 2);
assert.equal(changed.doc.features[1].depth, 0);
r = S.removeFeature(model, model.features[1].id);
assert.equal(r.ok, true);
assert.equal(r.doc.features.length, 1);
const removed = S.deleteObjects(model, [hole]);
assert.equal(removed.features.length, 1);
const old = S.clone(d); old.version = 1; delete old.features;
assert.equal(S.validateDoc(old).ok, true);
assert.equal(S.addFeature(old, "extrude", rect.lines, 10, "blind").doc.version, 2);
const plane = { origin: [0, 0, 20], u: [1, 0, 0], v: [0, 1, 0], normal: [0, 0, 1] };
const face = S.addFaceFeature(model, "extrude", plane, [[10, 10], [20, 10], [20, 20], [10, 20]], 5, "blind");
assert.equal(face.ok, true);
assert.equal(face.doc.version, 3);
assert.equal(S.validateDoc(face.doc).ok, true);
changed = S.convertUnits(face.doc, "cm");
assert.equal(changed.doc.faceFeatures[0].depth, .5);
assert.deepEqual(changed.doc.faceFeatures[0].plane.origin, [0, 0, 2]);
assert.deepEqual(changed.doc.faceFeatures[0].profile[0], [1, 1]);
assert.equal(S.removeFaceFeature(face.doc, face.doc.faceFeatures[0].id).doc.faceFeatures.length, 0);
assert.equal(S.removeFeature(face.doc, face.doc.features[0].id).doc.faceFeatures.length, 0);
const rounded = S.addRoundFeature(face.doc, [0, 0, 20], [100, 0, 20], 2);
assert.equal(rounded.ok, true);
assert.equal(rounded.doc.roundFeatures.length, 1);
assert.equal(S.validateDoc(rounded.doc).ok, true);
changed = S.convertUnits(rounded.doc, "cm");
assert.equal(changed.doc.roundFeatures[0].radius, .2);
assert.deepEqual(changed.doc.roundFeatures[0].a, [0, 0, 2]);
assert.equal(S.removeRoundFeature(rounded.doc, rounded.doc.roundFeatures[0].id).doc.roundFeatures.length, 0);
assert.equal(S.removeFeature(rounded.doc, rounded.doc.features[0].id).doc.roundFeatures.length, 0);
console.log("hq solid model checks ok");
