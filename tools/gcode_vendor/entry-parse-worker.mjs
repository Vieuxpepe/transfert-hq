import { createWorkerHandler } from '@chestnutlabs/gcode-parser';
import {
  createDialectRunner,
  cura,
  ideaMaker,
  klipper,
  marlin,
  orcaBambu,
  prusaSlicer,
  repRap,
  simplify3d,
  applyMarkerRanges,
  parseKeyValue,
} from '@chestnutlabs/gcode-dialects';
import { FeatureRole, MoveKind } from '@chestnutlabs/toolpath-core';

// Fallback adapter for FlashForge (FlashPrint / ffslicer / Orca-Flashforge) and
// bare slicer G-code using ;TYPE: or ;FEATURE: comments without an Orca/Prusa header.
// Runs at lower confidence ('inferred' / 'approximated') so full vendor adapters win when matched.
function flashforgeFallback() {
  const FEATURE_MAP = {
    'inner wall': FeatureRole.Perimeter,
    'perimeter': FeatureRole.Perimeter,
    'overhang wall': FeatureRole.Perimeter,
    'outer wall': FeatureRole.ExternalPerimeter,
    'external perimeter': FeatureRole.ExternalPerimeter,
    'sparse infill': FeatureRole.Infill,
    'infill': FeatureRole.Infill,
    'internal infill': FeatureRole.Infill,
    'gap infill': FeatureRole.Infill,
    'solid infill': FeatureRole.SolidInfill,
    'internal solid infill': FeatureRole.SolidInfill,
    'top surface': FeatureRole.SolidInfill,
    'top solid infill': FeatureRole.SolidInfill,
    'bottom surface': FeatureRole.SolidInfill,
    'ironing': FeatureRole.SolidInfill,
    'bridge': FeatureRole.Bridge,
    'bridge infill': FeatureRole.Bridge,
    'internal bridge': FeatureRole.Bridge,
    'support': FeatureRole.Support,
    'support material': FeatureRole.Support,
    'support interface': FeatureRole.Support,
    'support material interface': FeatureRole.Support,
    'support transition': FeatureRole.Support,
    'skirt': FeatureRole.Skirt,
    'skirt/brim': FeatureRole.Skirt,
    'brim': FeatureRole.Brim,
    'raft': FeatureRole.Raft,
    'prime tower': FeatureRole.PrimeTower,
    'wipe tower': FeatureRole.WipeTower,
    'custom': FeatureRole.Custom,
  };
  const state = new WeakMap();
  const st = (sink) => {
    let s = state.get(sink);
    if (!s) {
      s = { features: [], types: null, colours: null, printerModel: undefined };
      state.set(sink, s);
    }
    return s;
  };
  return {
    id: 'flashforge-generic',
    displayName: 'FlashForge / Slicer générique',
    kind: 'slicer',
    detect(input) {
      const m = /(generated by (?:ffslicer|FlashPrint|Orca-Flashforge)[^\n\r]*)/i.exec(input.headText);
      if (m) {
        return {
          dialectId: 'flashforge-generic',
          kind: 'slicer',
          confidence: 'inferred',
          evidence: m[1].trim(),
        };
      }
      if (/;\s*(?:TYPE|FEATURE)\s*:/.test(input.headText) || /;\s*filament_type\s*=/.test(input.headText)) {
        return {
          dialectId: 'flashforge-generic',
          kind: 'slicer',
          confidence: 'approximated',
          evidence: 'slicer comments',
        };
      }
      return null;
    },
    onComment(comment, srcByte, sink) {
      const s = st(sink);
      const trimmed = comment.trim();
      const feat = trimmed.startsWith('FEATURE:')
        ? trimmed.slice(8)
        : trimmed.startsWith('TYPE:')
          ? trimmed.slice(5)
          : null;
      if (feat !== null) {
        const role = FEATURE_MAP[feat.trim().toLowerCase()];
        s.features.push({ srcByte, value: role ?? FeatureRole.Custom });
        return;
      }
      const mmMatch = /^\s*filament used \[mm\]\s*=\s*([\d.]+)/i.exec(comment);
      if (mmMatch) {
        const v = Number(mmMatch[1]);
        if (Number.isFinite(v) && v >= 0) {
          sink.setFilamentUsage({
            lengthMm: v,
            source: { adapterId: 'flashforge-generic', evidence: '; filament used [mm]', srcByte },
          });
        }
        return;
      }
      const gMatch = /^\s*total filament used \[g\]\s*=\s*([\d.]+)/i.exec(comment);
      if (gMatch) {
        const v = Number(gMatch[1]);
        if (Number.isFinite(v) && v >= 0) {
          sink.setFilamentUsage({
            weightG: v,
            source: { adapterId: 'flashforge-generic', evidence: '; total filament used [g]', srcByte },
          });
        }
        return;
      }
      const kv = parseKeyValue(comment);
      if (!kv) return;
      if (kv.key === 'filament_type') {
        s.types = kv.value.split(';').map((v) => v.trim()).filter(Boolean);
      } else if (
        kv.key === 'filament_colour' ||
        kv.key === 'filament_color' ||
        kv.key === 'extruder_colour' ||
        kv.key === 'extruder_color'
      ) {
        s.colours = kv.value.split(';').map((v) => v.trim()).filter(Boolean);
      } else if (kv.key === 'printer_model' || kv.key === 'machine_type') {
        s.printerModel = kv.value;
      }
    },
    finalize(ir, sink) {
      const s = st(sink);
      const n = applyMarkerRanges(ir, s.features, (a, b, v) => sink.setFeature(a, b, v));
      if (n > 0) sink.upgradeCapability('featureRoles', 'inferred');
      const slots = Math.max(s.types?.length ?? 0, s.colours?.length ?? 0);
      for (let i = 0; i < Math.min(slots, 64); i++) {
        sink.setFilament({ slot: i, type: s.types?.[i], color: s.colours?.[i] });
        sink.setToolInfo(i, { material: s.types?.[i], colorHex: s.colours?.[i] });
      }
      if (s.printerModel) sink.setRaw('printer_model', s.printerModel);
    },
  };
}

const runner = createDialectRunner([
  prusaSlicer(),
  orcaBambu(),
  cura(),
  ideaMaker(),
  simplify3d(),
  flashforgeFallback(),
  klipper(),
  marlin(),
  repRap(),
]);

const post = (msg, transfer) => {
  if (msg && msg.type === 'done' && msg.ir && msg.ir.segments) {
    const cap = msg.ir.header?.capabilities?.featureRoles;
    if (cap === 'known' || cap === 'inferred') {
      const kind = msg.ir.segments.kind;
      const feat = msg.ir.segments.feature;
      for (let i = 0; i < msg.ir.segments.count; i++) {
        if ((kind[i] & MoveKind.Travel) !== 0) feat[i] = FeatureRole.Travel;
      }
    }
  }
  self.postMessage(msg, transfer);
};

const handle = createWorkerHandler(post, { dialects: runner });
self.onmessage = (ev) => handle(ev.data);
