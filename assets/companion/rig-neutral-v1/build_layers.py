"""Package existing textures as registered SVG layers; no generated anatomy.

The garment mask samples only the supplied original portrait. The other
textures are reconstructed layers saved by image_gen. No pixels are warped,
resampled, or repainted by this script.
"""
from pathlib import Path
import base64
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / "transferania-adult-neutral.jpg"
BODY_SCRIPT = ROOT.parents[2] / "scripts" / "build_rig_body_layers.py"


def uri(path):
    mime = "image/jpeg" if path.suffix == ".jpg" else "image/png"
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def svg(name, body):
    (ROOT / name).write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">'
        + body + '</svg>', encoding="utf-8"
    )


if BODY_SCRIPT.is_file():
    import subprocess
    import sys

    subprocess.run([sys.executable, str(BODY_SCRIPT)], check=True)

shutil.copyfile(SOURCE, ROOT / "source.jpg")
for name, x, y, width, height in [
    ("background", 0, 0, 512, 512),
    ("torso", 15.36, 174.08, 481.28, 368.64),
    ("lower-body", 0, 0, 512, 512),
    ("arm-left", 0, 0, 512, 512),
    ("arm-right", 0, 0, 512, 512),
    ("face", 25.6, -5.12, 460.8, 419.84),
    ("hair", 25.6, -5.12, 460.8, 471.04),
]:
    body = f'<image href="{uri(ROOT / (name + ".png"))}" x="{x}" y="{y}" width="{width}" height="{height}" preserveAspectRatio="none"/>'
    if name == "torso":
        # Original Transferania plate (source.jpg) — not the black satin torso PNG + vector fill.
        body = f'<image href="{uri(SOURCE)}" x="0" y="0" width="512" height="512" preserveAspectRatio="none"/>'
    svg(name + ".svg", body)

# Follow the original clothed garment's outside contour. The upper edge
# crosses bare neckline skin only where the clothed underpainting continues;
# there is no room, face, hair, or circular portrait copied into this layer.
outline = (
    "M94 338 L106 320 Q137 311 169 317 Q186 312 208 301 "
    "Q249 280 286 291 Q312 301 337 323 L363 320 Q384 323 399 347 "
    "C424 381 425 431 405 457 C378 485 333 496 293 478 "
    "Q279 475 269 462 Q256 453 241 462 C226 482 179 495 130 488 "
    "C82 484 49 465 42 431 C34 399 48 356 94 338 Z"
)
svg("garment-front.svg",
    '<defs><filter id="soft" x="-2%" y="-2%" width="104%" height="104%"><feGaussianBlur stdDeviation=".7"/></filter>'
    '<linearGradient id="neck" gradientUnits="userSpaceOnUse" x1="0" y1="285" x2="0" y2="330">'
    '<stop offset="0" stop-color="white" stop-opacity="0"/><stop offset="1" stop-color="white"/></linearGradient>'
    '<mask id="cut" maskUnits="userSpaceOnUse" x="0" y="0" width="512" height="512">'
    f'<path d="{outline}" fill="url(#neck)" filter="url(#soft)"/></mask></defs>'
    f'<image href="{uri(SOURCE)}" width="512" height="512" mask="url(#cut)"/>')

manifest = {
    "name": "Transferania neutral layer study 01",
    "status": "eight_layer_opt_in_rig",
    "canvas": [512, 512],
    "source": "source.jpg",
    "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
    "layers": [
        {"file": name + ".svg", "role": role}
        for name, role in [
            ("background", "reconstructed background"),
            ("torso", "clothed underpainting"),
            ("lower-body", "generated hips and thighs continuation"),
            ("arm-left", "generated left upper arm"),
            ("arm-right", "generated right upper arm"),
            ("face", "reconstructed face and neck"),
            ("garment-front", "masked original garment-front pixels"),
            ("hair", "reconstructed hair"),
        ]
    ],
    "registration": "Full-canvas SVGs with embedded image textures; generated textures are registered approximately to the supplied source.",
    "garment": "Existing supplied artwork and clothing coverage preserved. No garment or anatomy generated by this script.",
    "production": "Available in the live HQ companion through Outils > Calques. The toggle restores the prior flat portrait when switched off. Textures load only when selected."
}
(ROOT / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
print("Packaged eight registered SVG layers, original source and manifest")
